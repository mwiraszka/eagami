// Parses the @eagami/ui CHANGELOG.md (Keep a Changelog format) into a typed
// dataset the website renders on its changelog page. Run via `docs:changelog`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, '../CHANGELOG.md');
const OUT = resolve(here, '../../../apps/website/src/app/data/changelog.generated.ts');

// The page reads as a history of the current major line; everything below this
// predates the API the site documents.
const MIN_MAJOR = 5;

const lines = readFileSync(SRC, 'utf8').split(/\r?\n/);

const releases = [];
let release = null;
let section = null;

for (const line of lines) {
  const versionMatch = /^## \[(.+?)\](?: - (.+))?$/.exec(line);
  if (versionMatch) {
    if (Number.parseInt(versionMatch[1], 10) < MIN_MAJOR) {
      break;
    }
    release = { version: versionMatch[1], date: versionMatch[2] ?? '', sections: [] };
    releases.push(release);
    section = null;
    continue;
  }
  // Footer link definitions (`[1.2.0]: https://...`) end the entries.
  if (/^\[[^\]]+\]:\s/.test(line)) {
    break;
  }
  if (!release) {
    continue;
  }
  const sectionMatch = /^### (.+)$/.exec(line);
  if (sectionMatch) {
    section = { heading: sectionMatch[1].trim(), entries: [] };
    release.sections.push(section);
    continue;
  }
  const entryMatch = /^- (.+)$/.exec(line);
  if (entryMatch && section) {
    section.entries.push(entryMatch[1].trim());
  }
}

const types = `export interface ChangelogSection {
  heading: string;
  entries: string[];
}

export interface ChangelogRelease {
  version: string;
  date: string;
  sections: ChangelogSection[];
}
`;

const banner = `// AUTO-GENERATED by packages/ui/scripts/extract-changelog.mjs; do not edit by hand.
// Regenerate with: pnpm --filter @eagami/ui docs:changelog
`;

const body = `export const UI_CHANGELOG: readonly ChangelogRelease[] = ${JSON.stringify(
  releases,
  null,
  2,
)};
`;

writeFileSync(OUT, `${banner}\n${types}\n${body}`);
console.log(`Wrote ${releases.length} releases to ${OUT}`);
